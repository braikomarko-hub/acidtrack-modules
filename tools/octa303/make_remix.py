#!/usr/bin/env python3
"""Write OCTA303's playing remix from Tim Hastie's `octatrick` remix -- the one whose FX2 chooser
already worked on the author's MKI -- so the effect keys are never guessed.

    python3 tools/octa303/make_remix.py                     -> remixes/octa303-live/
    python3 tools/octa303/make_remix.py --add "KEY" ...     -> the same, plus those modules
                                                               (e.g. the USB audio out of the master)
    python3 tools/octa303/make_remix.py --remove "KEY" ...  -> the same, without those modules

Run from the octabam root.  The octatrick remix is read, never written.  SYNTH MACHINE (and any
module OCTA303 declares a conflict with) is dropped, OCTA303 is added, and every other field of
the remix -- its modules and their order (the FX2 chooser's rows), its fallback, its FX1 rows --
is kept as Tim composed it.  Then: make docs && make check REMIX=octa303-live.
"""
import dataclasses, os, runpy, sys
from pathlib import Path

ROOT = Path.cwd()
SRC = ROOT / 'remixes' / 'octatrick' / 'remix.py'
if not SRC.exists() or not (ROOT / 'tools' / 'remix' / 'schema.py').exists():
    sys.exit('run from the octabam root (remixes/octatrick/remix.py not found)')
sys.path.insert(0, str(ROOT / 'tools'))
from remix.schema import Remix  # noqa: E402

extra = [sys.argv[i + 1] for i, a in enumerate(sys.argv[:-1]) if a == '--add']
less = [sys.argv[i + 1] for i, a in enumerate(sys.argv[:-1]) if a == '--remove']
base = runpy.run_path(str(SRC), run_name='remix_octatrick')['REMIX']
man = runpy.run_path(str(ROOT / 'modules' / 'octa303' / 'manifest.py'), run_name='remix_manifest_octa303')['MODULE']
drop = {k for k, _why in man.conflicts}
unknown = [k for k in less if k not in base.modules]
if unknown:
    sys.exit('--remove: %s not in octatrick (its modules: %s)' % (unknown, list(base.modules)))
mods = [k for k in base.modules if k not in drop and k not in less]
removed = [k for k in base.modules if k in drop or k in less]
if 'OCTA303' not in mods:
    mods.append('OCTA303')
for k in extra:
    if k in drop:
        sys.exit('%r conflicts with OCTA303' % k)
    if k not in mods:
        mods.append(k)
name = 'octa303-live'

lines, skipped = [], []
for f in dataclasses.fields(Remix):
    if f.name in ('name', 'doc', 'modules', 'proof', 'proof_note'):
        continue
    v = getattr(base, f.name)
    default = f.default if f.default is not dataclasses.MISSING else (
        f.default_factory() if f.default_factory is not dataclasses.MISSING else object())
    if f.name != 'fallback' and v == default:
        continue
    r = repr(v)
    if '<' in r:
        skipped.append(f.name); continue
    if f.name == 'fx1' and isinstance(v, tuple):
        v = tuple(k for k in v if k not in drop and k not in less); r = repr(v)
    lines.append('    %s=%s,' % (f.name, r))
if skipped:
    sys.exit('octatrick sets %s in a form this script cannot copy: write the remix by hand' % skipped)

doc = ('OCTA303 (the TB-303) with octatrick\'s other modules and its FX2 chooser'
       + (' plus %s' % ', '.join(extra) if extra else '')
       + (', without %s' % ', '.join(less) if less else '')
       + '; SYNTH MACHINE is out, it shares OCTA303\'s hooks.')
out = ROOT / 'remixes' / name
out.mkdir(parents=True, exist_ok=True)
(out / 'remix.py').write_text('''"""Generated by tools/octa303/make_remix.py from remixes/octatrick/remix.py; regenerate, don't edit."""
from remix.schema import Proof, Remix

REMIX = Remix(
    name=%r,
    doc=%r,
    modules=%r,
%s
    proof=Proof.RENDER,
    proof_note="composed from octatrick's remix; run `make check REMIX=%s` before any unit",
)
''' % (name, doc, tuple(mods), '\n'.join(lines), name))
(out / 'README.md').write_text('''# %s

%s

Modules, in order (the FX2 chooser's rows are the effects among them):

%s

Generated by `tools/octa303/make_remix.py` from `remixes/octatrick/remix.py`
(removed: %s). Build and check:

    make docs && make check REMIX=%s
''' % (name, doc, '\n'.join('- `%s`' % k for k in mods), ', '.join(removed) or 'nothing', name))
print('wrote %s/remix.py and README.md' % out.relative_to(ROOT))
print('  removed :', removed or 'nothing')
print('  modules :', mods)
